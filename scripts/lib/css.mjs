// Renders the token model as CSS custom properties (research report §4.1).
//
// Appearance selection:
//   :root                                     core tokens + light
//   prefers-color-scheme: dark                dark, unless data-theme="light"
//   [data-theme="dark"] / [data-theme="light"] site override of the OS setting (LIB-15)
//   prefers-contrast: more                    the increased-contrast set for the active scheme (ACC-18)
//   prefers-reduced-motion: reduce            the tokens' reducedMotion values (MOT-02)
// Every appearance block has the same specificity (0,2,0) except :root, so the later
// block wins and the contrast blocks refine whichever scheme is active.

import { MODES } from './tokens.mjs';

const PREFIX = '--sdk-';
const GENERIC_FAMILIES = new Set(['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'math', 'emoji', 'fangsong']);

/** The custom property name for a token path, e.g. ['color', 'label'] → --sdk-color-label. */
export const cssName = (path) => `${PREFIX}${path.join('-')}`;

const num = (n) => String(Number(n.toFixed(4)));
// A zero length may drop its unit; a zero <time> may not (`transition-duration: 0` is invalid).
const dimension = ({ value, unit }) => (value === 0 && unit !== 'ms' && unit !== 's' ? '0' : `${num(value)}${unit}`);
const channel = (c) => Math.round(c * 255);

function color({ components, alpha = 1 }) {
  const [r, g, b] = components.map(channel);
  if (alpha < 1) return `rgb(${r} ${g} ${b} / ${num(alpha)})`;
  return `#${[r, g, b].map((c) => c.toString(16).padStart(2, '0')).join('')}`;
}

const family = (name) => (GENERIC_FAMILIES.has(name) ? name : `"${name.replace(/"/g, '\\"')}"`);

/** Formats one resolved value of `type` as CSS. `extensions` carries kit hints such as `unit`. */
export function cssValue(type, value, extensions = {}) {
  switch (type) {
    case 'color':
      return color(value);
    case 'dimension':
    case 'duration':
      return dimension(value);
    case 'number':
      return extensions.unit ? `${num(value)}${extensions.unit}` : num(value);
    case 'fontWeight':
      return String(value);
    case 'fontFamily':
      return (Array.isArray(value) ? value : [value]).map(family).join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.map(num).join(', ')})`;
    case 'shadow':
      return (Array.isArray(value) ? value : [value])
        .map((s) => [s.offsetX, s.offsetY, s.blur, s.spread].map(dimension).concat(color(s.color)).join(' '))
        .join(', ');
    default:
      throw new Error(`no CSS format for $type ${type}`);
  }
}

/** The CSS for one token: an alias becomes var() so overrides of its target cascade to it. */
function declaration(token) {
  let value;
  if (token.alias) {
    value = `var(${cssName(token.alias.split('.'))})`;
  } else if (token.extensions.fluid) {
    const { min, preferred } = token.extensions.fluid;
    value = `clamp(${dimension(min)}, ${preferred}, ${dimension(token.value)})`;
  } else {
    value = cssValue(token.type, token.value, token.extensions);
  }
  return `  ${cssName(token.path)}: ${value};`;
}

const block = (selector, lines, indent = '') => [
  `${indent}${selector} {`,
  ...lines.map((line) => `${indent}${line}`),
  `${indent}}`,
];
const media = (query, selector, lines) => [`@media ${query} {`, ...block(selector, lines, '  '), '}'];

/** Renders the whole stylesheet. The output is deterministic: no dates, sorted only by source order. */
export function renderCss(model) {
  const mode = (id) => model.modes[id].map(declaration);
  const reduced = model.core
    .filter((token) => token.extensions.reducedMotion !== undefined)
    .map((token) => declaration({ ...token, alias: null, extensions: {}, value: token.extensions.reducedMotion }));
  const notThemed = (theme) => `:root:not([data-theme="${theme}"])`;
  const themed = (theme) => `:root[data-theme="${theme}"]`;
  const [light, dark, lightHc, darkHc] = MODES.map((m) => m.id);

  const sections = [
    [
      '/*',
      ' * storefront-design-kit design tokens.',
      ' * Generated by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit:',
      ' * change the token files and run `npm run tokens`.',
      ' *',
      ' * Appearance follows the OS. Set data-theme="light" or "dark" on <html> to override it.',
      ' */',
    ],
    block(':root', ['  color-scheme: light dark;', ...model.core.map(declaration), ...mode(light)]),
    block(themed('light'), ['  color-scheme: light;']),
    media('(prefers-color-scheme: dark)', notThemed('light'), mode(dark)),
    block(themed('dark'), ['  color-scheme: dark;', ...mode(dark)]),
    media('(prefers-contrast: more) and (prefers-color-scheme: light)', notThemed('dark'), mode(lightHc)),
    media('(prefers-contrast: more)', themed('light'), mode(lightHc)),
    media('(prefers-contrast: more) and (prefers-color-scheme: dark)', notThemed('light'), mode(darkHc)),
    media('(prefers-contrast: more)', themed('dark'), mode(darkHc)),
  ];
  if (reduced.length) sections.push(media('(prefers-reduced-motion: reduce)', ':root', reduced));
  return `${sections.map((lines) => lines.join('\n')).join('\n\n')}\n`;
}
